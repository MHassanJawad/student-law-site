// Write docs/THIRD_PARTY_LICENSES.md from package-lock.json and flag copyleft licences for review.
import { readFile, writeFile } from "node:fs/promises";

const lock = JSON.parse(await readFile(new URL("../package-lock.json", import.meta.url), "utf8"));
const COPYLEFT = /\b(A?GPL|LGPL|MPL|EPL|CDDL|SSPL|EUPL)\b/i;
const rows = new Map();
for (const [path, meta] of Object.entries(lock.packages ?? {})) {
  if (!path.includes("node_modules/") || meta.link) continue;
  const name = meta.name ?? path.slice(path.lastIndexOf("node_modules/") + "node_modules/".length);
  const key = `${name}@${meta.version}`;
  if (!rows.has(key) || !meta.dev) rows.set(key, { name, version: meta.version, license: meta.license ?? "UNKNOWN", dev: Boolean(meta.dev) });
}
const sorted = [...rows.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
const runtime = sorted.filter((row) => !row.dev);
const flagged = sorted.filter((row) => COPYLEFT.test(row.license) || row.license === "UNKNOWN");
const counts = Object.entries(runtime.reduce((all, row) => ({ ...all, [row.license]: (all[row.license] ?? 0) + 1 }), {}))
  .sort((a, b) => b[1] - a[1]);
const table = (items) => items.map((row) => `| ${row.name} | ${row.version} | ${row.license} |`).join("\n");

await writeFile(new URL("../docs/THIRD_PARTY_LICENSES.md", import.meta.url), `# Third-party licences

Generated by \`node scripts/list-licenses.mjs\` from \`package-lock.json\`; rerun after dependency changes. Licence values are the identifiers declared by each package and are not a legal review.

## Summary of runtime packages

${runtime.length} packages are installed for production use (build and runtime, excluding development-only tools).

| Licence | Packages |
| --- | --- |
${counts.map(([license, count]) => `| ${license} | ${count} |`).join("\n")}

## Packages needing review

Copyleft or undeclared licences, in any dependency group. A package listed here may still be acceptable, for example when a dual licence permits a permissive choice or the code is used only as a development tool, but the decision should be recorded.

| Package | Version | Licence |
| --- | --- | --- |
${table(flagged) || "| None | | |"}

## Runtime packages

| Package | Version | Licence |
| --- | --- | --- |
${table(runtime)}
`);
process.stdout.write(`${runtime.length} runtime packages, ${flagged.length} flagged for review.\n`);
